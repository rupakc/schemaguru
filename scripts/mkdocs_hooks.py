"""MkDocs hooks: publish ``site-demo/`` (outside ``docs/``) as ``demo-assets/`` in the site.

The demo's assets live at the repository root (spec 23.1 layout) and are regenerated by
``scripts/build_demo_export.py``; this hook adds them to the build so ``docs/demo.md`` can load
them without copying files into ``docs/``.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from mkdocs.structure.files import File, Files

DEMO = Path(__file__).resolve().parent.parent / "site-demo"
DEST = "demo-assets"


def on_files(files: Files, config: Any) -> Files:
    for path in sorted(DEMO.iterdir()):
        if path.is_file() and path.suffix in {".js", ".css", ".json"}:
            files.append(File.generated(config, f"{DEST}/{path.name}", abs_src_path=str(path)))
    return files
