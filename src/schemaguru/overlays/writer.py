"""Machine-owned overlay files (spec 14.2).

SchemaGuru never edits a human file. It writes only files it owns: a file is machine-owned if
it carries the header marker; anything else at the target path is refused with an error.
"""

from __future__ import annotations

import os
import tempfile
from collections.abc import Iterable
from pathlib import Path
from typing import Any

import yaml

from schemaguru.errors import SchemaGuruError
from schemaguru.model.facts import Fact
from schemaguru.model.joins import JoinRef
from schemaguru.model.refs import ObjectRef

ACCEPTED_HEADER = "# generated by schemaguru accept — do not hand-edit\n"
DRAFTS_HEADER = "# generated by schemaguru export-drafts — do not hand-edit; review and copy\n"
_MARKER = "# generated by schemaguru"


def _is_machine_owned(path: Path) -> bool:
    try:
        with path.open(encoding="utf-8") as fh:
            return fh.readline().startswith(_MARKER)
    except (OSError, UnicodeDecodeError):
        return False


def _guard(path: Path) -> None:
    if path.exists() and not _is_machine_owned(path):
        raise SchemaGuruError(
            f"refusing to overwrite {path}: it is not a machine-owned file "
            f"(it must start with '{_MARKER}'); SchemaGuru never edits human overlays"
        )


def _table_entry(doc: dict[str, Any], table: ObjectRef) -> dict[str, Any]:
    table = table.table_ref()
    tables: dict[str, Any] = doc.setdefault("tables", {})
    entry: dict[str, Any] = tables.setdefault(table.canonical(), {})
    return entry


def _col_entry(entry: dict[str, Any], name: str) -> dict[str, Any]:
    col: dict[str, Any] = entry.setdefault("columns", {}).setdefault(name, {})
    return col


def facts_to_overlay(facts: Iterable[Fact]) -> dict[str, Any]:
    """Render facts as an overlay document (kinds with no overlay form are skipped)."""
    doc: dict[str, Any] = {"version": 1}
    for f in facts:
        kind, v, subj = f.kind.name, f.value, f.subject
        if isinstance(subj, JoinRef):
            if kind != "JOIN":
                continue
            left_table = subj.left[0].table_ref()
            entry = _table_entry(doc, left_table)
            j: dict[str, Any] = {
                "to": [c.canonical() for c in subj.right]
                if len(subj.right) > 1
                else subj.right[0].canonical(),
                "from": [c.column for c in subj.left]
                if len(subj.left) > 1
                else subj.left[0].column,
            }
            if v.get("cardinality"):
                j["cardinality"] = v["cardinality"]
            if subj.cast_to:
                j["cast_to"] = subj.cast_to
            entry.setdefault("joins", []).append(j)
            continue
        if kind == "GLOSSARY":
            g: dict[str, Any] = {"term": v["term"], "definition": v["definition"]}
            maps = [ObjectRef.from_dict(m).canonical() for m in v.get("maps_to") or []]
            if maps:
                g["maps_to"] = maps
            doc.setdefault("glossary", []).append(g)
            continue
        if kind == "NEVER_QUERY":
            doc.setdefault("never_query", []).append(
                {"table": subj.table_ref().canonical(), "reason": v["reason"]}
            )
            continue
        if subj.column is not None:
            col_name = subj.column
            centry = _col_entry(_table_entry(doc, subj), col_name)
            if kind == "DESCRIPTION":
                centry["description"] = v["text"]
            elif kind == "VALUES":
                centry["values"] = list(v["values"])
                if v.get("split"):
                    centry["values_split"] = v["split"]
            elif kind == "TYPE_NOTE":
                centry["type_note"] = v.get("means") or v.get("stored_as")
            else:
                # drop the empty column entry we just created for an unsupported kind
                _table_entry(doc, subj)["columns"].pop(col_name, None)
            continue
        entry = _table_entry(doc, subj)
        if kind == "DESCRIPTION":
            entry["description"] = v["text"]
        elif kind == "USE_CASES":
            entry["use_cases"] = list(v["questions"])
        elif kind == "ENTITY_TYPE":
            entry["entity_type"] = v["entity"]
        elif kind == "SOFT_DELETE":
            entry["soft_delete"] = v["predicate"]
        elif kind == "PITFALL":
            p: dict[str, Any] = {"rule": v["rule"]}
            if v.get("fix"):
                p["fix"] = v["fix"]
            if v.get("severity") and v["severity"] != "warn":
                p["severity"] = v["severity"]
            entry.setdefault("pitfalls", []).append(p)
    for t, entry in list(doc.get("tables", {}).items()):
        if "columns" in entry and not entry["columns"]:
            del entry["columns"]
        if not entry:
            del doc["tables"][t]
    if not doc.get("tables"):
        doc.pop("tables", None)
    return doc


def _merge(base: dict[str, Any], new: dict[str, Any]) -> dict[str, Any]:
    """Merge ``new`` into ``base``: scalars are replaced, lists are unioned, maps recurse."""
    for key, val in new.items():
        cur = base.get(key)
        if isinstance(val, dict) and isinstance(cur, dict):
            _merge(cur, val)
        elif isinstance(val, list) and isinstance(cur, list):
            cur.extend(item for item in val if item not in cur)
        else:
            base[key] = val
    return base


def _dump(doc: dict[str, Any], header: str) -> str:
    body = yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, default_flow_style=False)
    return header + body


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def export_drafts(facts: Iterable[Fact], path: str | Path) -> Path:
    """Write ``facts`` as a review draft at ``path`` (replaced wholesale on every export).

    Refuses (``SchemaGuruError``) to touch a file that is not machine-owned.
    """
    target = Path(path)
    _guard(target)
    _atomic_write(target, _dump(facts_to_overlay(facts), DRAFTS_HEADER))
    return target


def append_accepted(facts: Iterable[Fact], path: str | Path = "schemaguru/accepted.yaml") -> Path:
    """Add ``facts`` to the machine-owned accepted overlay, creating it if needed.

    Refuses (``SchemaGuruError``) to touch a file that is not machine-owned.
    """
    target = Path(path)
    _guard(target)
    doc: dict[str, Any] = {"version": 1}
    if target.exists():
        try:
            existing = yaml.safe_load(target.read_text(encoding="utf-8"))
        except (OSError, yaml.YAMLError, UnicodeDecodeError) as e:
            raise SchemaGuruError(f"cannot read machine-owned file {target}: {e}") from e
        if isinstance(existing, dict):
            doc = existing
    _merge(doc, facts_to_overlay(facts))
    _atomic_write(target, _dump(doc, ACCEPTED_HEADER))
    return target
