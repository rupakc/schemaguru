from __future__ import annotations

from pathlib import Path

import pytest

from schemaguru.errors import SchemaGuruError
from schemaguru.model.facts import Fact, Provenance, Status
from schemaguru.model.kinds import FactKind
from schemaguru.model.refs import ObjectRef
from schemaguru.overlays import append_accepted, export_drafts, load_overlays
from schemaguru.store.sqlite import SQLiteStore

from .conftest import FIXTURES

ORD = ObjectRef(None, "shop", "orders")


def test_writer_never_edits_human_file(tmp_path: Path) -> None:
    human = tmp_path / "schemaguru.yaml"
    original = "version: 1\n# my notes\ntables: {}\n"
    human.write_text(original)
    f = Fact.make(FactKind.DESCRIPTION, ORD, {"text": "x"}, Provenance.DRAFTED, Status.UNVERIFIED)
    with pytest.raises(SchemaGuruError):
        append_accepted([f], human)
    with pytest.raises(SchemaGuruError):
        export_drafts([f], human)
    assert human.read_text() == original
    assert [p.name for p in tmp_path.iterdir()] == ["schemaguru.yaml"]  # no stray temp files


def test_roundtrip_through_machine_file(store: SQLiteStore, tmp_path: Path) -> None:
    facts, *_ = load_overlays([FIXTURES / "overlays" / "spec_example.yaml"], store)
    out = tmp_path / "schemaguru" / "accepted.yaml"
    append_accepted(facts, out)
    assert out.read_text().startswith("# generated by schemaguru accept — do not hand-edit")
    again, *_, bag = load_overlays([out], store)
    assert list(bag) == []
    assert {f.id for f in again} == {f.id for f in facts}
    # appending the same facts again changes nothing; new facts are merged in
    before = out.read_text()
    append_accepted(facts, out)
    assert out.read_text() == before
    extra = Fact.make(FactKind.DESCRIPTION, ObjectRef(None, "shop", "payments"), {"text": "p"},
                      Provenance.HUMAN, Status.UNVERIFIED)  # fmt: skip
    append_accepted([extra], out)
    merged, *_ = load_overlays([out], store)
    assert extra.id in {f.id for f in merged} and len(merged) == len(facts) + 1


def test_export_drafts_replaces_own_file(store: SQLiteStore, tmp_path: Path) -> None:
    out = tmp_path / "drafts" / "d.yaml"
    f1 = Fact.make(
        FactKind.DESCRIPTION, ORD, {"text": "one"}, Provenance.DRAFTED, Status.UNVERIFIED
    )
    f2 = Fact.make(
        FactKind.DESCRIPTION, ORD, {"text": "two"}, Provenance.DRAFTED, Status.UNVERIFIED
    )
    export_drafts([f1], out)
    export_drafts([f2], out)
    text = out.read_text()
    assert "two" in text and "one" not in text and text.startswith("# generated by schemaguru")


def test_each_writer_refuses_the_others_file(tmp_path: Path) -> None:
    f = Fact.make(FactKind.DESCRIPTION, ORD, {"text": "x"}, Provenance.DRAFTED, Status.UNVERIFIED)
    acc, drafts = tmp_path / "accepted.yaml", tmp_path / "drafts.yaml"
    append_accepted([f], acc)
    export_drafts([f], drafts)
    a_before, d_before = acc.read_text(), drafts.read_text()
    with pytest.raises(SchemaGuruError):
        export_drafts([f], acc)
    with pytest.raises(SchemaGuruError):
        append_accepted([f], drafts)
    assert acc.read_text() == a_before and drafts.read_text() == d_before
