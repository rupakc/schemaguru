from __future__ import annotations

from pathlib import Path

import pytest

from schemaguru.errors import SchemaGuruError
from schemaguru.model.facts import Fact, Provenance, Status
from schemaguru.model.kinds import FactKind
from schemaguru.model.refs import ObjectRef
from schemaguru.overlays import append_accepted, export_drafts, load_overlays
from schemaguru.store.sqlite import SQLiteStore

from .conftest import FIXTURES

ORD = ObjectRef(None, "shop", "orders")


def test_writer_never_edits_human_file(tmp_path: Path) -> None:
    human = tmp_path / "schemaguru.yaml"
    original = "version: 1\n# my notes\ntables: {}\n"
    human.write_text(original, encoding="utf-8")
    f = Fact.make(FactKind.DESCRIPTION, ORD, {"text": "x"}, Provenance.DRAFTED, Status.UNVERIFIED)
    with pytest.raises(SchemaGuruError):
        append_accepted([f], human)
    with pytest.raises(SchemaGuruError):
        export_drafts([f], human)
    assert human.read_text(encoding="utf-8") == original
    assert [p.name for p in tmp_path.iterdir()] == ["schemaguru.yaml"]  # no stray temp files


def test_roundtrip_through_machine_file(store: SQLiteStore, tmp_path: Path) -> None:
    facts, *_ = load_overlays([FIXTURES / "overlays" / "spec_example.yaml"], store)
    out = tmp_path / "schemaguru" / "accepted.yaml"
    append_accepted(facts, out)
    assert out.read_text(encoding="utf-8").startswith(
        "# generated by schemaguru accept — do not hand-edit"
    )
    again, *_, bag = load_overlays([out], store)
    assert list(bag) == []
    assert {f.id for f in again} == {f.id for f in facts}
    # appending the same facts again changes nothing; new facts are merged in
    before = out.read_text(encoding="utf-8")
    append_accepted(facts, out)
    assert out.read_text(encoding="utf-8") == before
    extra = Fact.make(FactKind.DESCRIPTION, ObjectRef(None, "shop", "payments"), {"text": "p"},
                      Provenance.HUMAN, Status.UNVERIFIED)  # fmt: skip
    append_accepted([extra], out)
    merged, *_ = load_overlays([out], store)
    assert extra.id in {f.id for f in merged} and len(merged) == len(facts) + 1


def test_export_drafts_replaces_own_file(store: SQLiteStore, tmp_path: Path) -> None:
    out = tmp_path / "drafts" / "d.yaml"
    f1 = Fact.make(
        FactKind.DESCRIPTION, ORD, {"text": "one"}, Provenance.DRAFTED, Status.UNVERIFIED
    )
    f2 = Fact.make(
        FactKind.DESCRIPTION, ORD, {"text": "two"}, Provenance.DRAFTED, Status.UNVERIFIED
    )
    export_drafts([f1], out)
    export_drafts([f2], out)
    text = out.read_text(encoding="utf-8")
    assert "two" in text and "one" not in text and text.startswith("# generated by schemaguru")


def test_each_writer_refuses_the_others_file(tmp_path: Path) -> None:
    f = Fact.make(FactKind.DESCRIPTION, ORD, {"text": "x"}, Provenance.DRAFTED, Status.UNVERIFIED)
    acc, drafts = tmp_path / "accepted.yaml", tmp_path / "drafts.yaml"
    append_accepted([f], acc)
    export_drafts([f], drafts)
    a_before, d_before = acc.read_text(encoding="utf-8"), drafts.read_text(encoding="utf-8")
    with pytest.raises(SchemaGuruError):
        export_drafts([f], acc)
    with pytest.raises(SchemaGuruError):
        append_accepted([f], drafts)
    assert (
        acc.read_text(encoding="utf-8") == a_before
        and drafts.read_text(encoding="utf-8") == d_before
    )


def test_unwritable_kinds_reported(caplog: pytest.LogCaptureFixture) -> None:
    from schemaguru.overlays.writer import facts_to_overlay, unwritable_kinds

    pk = [
        Fact.make(FactKind.PRIMARY_KEY, ORD, {"columns": ["order_id"]}, Provenance.DRAFTED,
                  Status.UNVERIFIED)
        for _ in range(1)
    ]  # fmt: skip
    pk2 = Fact.make(
        FactKind.PRIMARY_KEY, ObjectRef(None, "shop", "customers"), {"columns": ["customer_id"]},
        Provenance.DRAFTED, Status.UNVERIFIED,
    )  # fmt: skip
    ok = Fact.make(FactKind.DESCRIPTION, ORD, {"text": "x"}, Provenance.DRAFTED, Status.UNVERIFIED)
    with caplog.at_level("WARNING", logger="schemaguru.overlays.writer"):
        facts_to_overlay([*pk, pk2, ok])
    recs = [r for r in caplog.records if r.name == "schemaguru.overlays.writer"]
    assert len(recs) == 1 and recs[0].levelname == "WARNING"
    assert "PRIMARY_KEY" in recs[0].getMessage() and "2" in recs[0].getMessage()
    assert unwritable_kinds([*pk, pk2, ok]) == {"PRIMARY_KEY": 2}
    caplog.clear()
    facts_to_overlay([ok])
    assert not caplog.records


def test_changed_join_replaces(tmp_path: Path) -> None:
    from schemaguru.model.joins import JoinRef

    j = JoinRef(
        (ObjectRef(None, "shop", "orders", "customer_id"),),
        (ObjectRef(None, "shop", "customers", "customer_id"),),
    )
    out = tmp_path / "accepted.yaml"
    for card in ("N:1", "1:1"):
        f = Fact.make(FactKind.JOIN, j, {"cardinality": card}, Provenance.HUMAN, Status.UNVERIFIED)
        append_accepted([f], out)
    import yaml

    doc = yaml.safe_load(out.read_text(encoding="utf-8"))
    assert doc["tables"]["shop.orders"]["joins"] == [
        {"to": "shop.customers.customer_id", "from": "customer_id", "cardinality": "1:1"}
    ]


def test_atomic_write_mode_and_recheck(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    import os
    import stat

    f = Fact.make(FactKind.DESCRIPTION, ORD, {"text": "x"}, Provenance.DRAFTED, Status.UNVERIFIED)
    old = os.umask(0o022)
    try:
        new = tmp_path / "new.yaml"
        append_accepted([f], new)
        assert stat.S_IMODE(new.stat().st_mode) == 0o644
        existing = tmp_path / "existing.yaml"
        append_accepted([f], existing)
        existing.chmod(0o664)
        append_accepted([f], existing)
        assert stat.S_IMODE(existing.stat().st_mode) == 0o664
    finally:
        os.umask(old)
    # the ownership header is re-checked right before the replace
    target = tmp_path / "race.yaml"
    append_accepted([f], target)
    real_chmod = os.chmod

    def racing_chmod(path: object, mode: int, *a: object, **k: object) -> None:
        real_chmod(path, mode, *a, **k)  # type: ignore[arg-type]
        if str(path).endswith(".tmp"):
            target.write_text("version: 1\n# a human took this file\n", encoding="utf-8")

    monkeypatch.setattr(os, "chmod", racing_chmod)
    with pytest.raises(SchemaGuruError):
        append_accepted([f], target)
    monkeypatch.undo()
    assert "a human took this file" in target.read_text(encoding="utf-8")
    assert [p.name for p in tmp_path.glob(".*tmp")] == []
